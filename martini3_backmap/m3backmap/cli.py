"""Command line interface.

    python -m m3backmap backmap  -c cg.gro -o aa.gro [options]
    python -m m3backmap make-map -f molecule_aa.pdb -b beads.ndx -n POPC -o POPC.map
    python -m m3backmap merge    -f protein.gro rest.gro -o system.gro
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np

from . import __version__
from .backmap import Options, backmap, read_itp_orders, reorder_residues
from .structure import System, read_structure, write_gro, write_pdb, write_structure
from .templates import load_maps, make_map, read_bead_definitions
from .solvent import WATER_MODELS, ION_NAMES


def _cmd_backmap(a) -> int:
    cg = read_structure(a.cg)
    maps = load_maps(a.mapdir or [], a.maps or [])
    opts = Options(water_model=a.water, water_resname=a.water_resname, ion_names=a.ions,
                   ion_waters=a.ion_waters, relax=not a.no_relax, relax_iter=a.relax_iter,
                   max_bb_distance=a.bb_break, prune_water=a.prune_water,
                   skip_unknown=a.skip_unknown, group_molecules=not a.keep_order, seed=a.seed, verbose=not a.quiet)
    print(f"Read {cg.n_atoms} beads in {len(cg.residues)} residues from {a.cg}", file=sys.stderr)
    print(f"Templates available for: {', '.join(sorted(maps)) or '(none)'}", file=sys.stderr)
    aa, rep = backmap(cg, maps, opts)
    if a.itp:
        for m in reorder_residues(aa, read_itp_orders(a.itp)):
            print("WARNING:", m, file=sys.stderr)
    write_structure(aa, a.out)
    base, _ = os.path.splitext(a.out)
    prot = [r for r in aa.residues if r.chain]
    rest = [r for r in aa.residues if not r.chain]
    if prot and rest:
        write_pdb(System(aa.title, prot, aa.box), base + "_protein.pdb")
        write_gro(System(aa.title, rest, aa.box), base + "_nonprotein.gro")
    elif prot:
        write_pdb(System(aa.title, prot, aa.box), base + "_protein.pdb")

    print(f"\nWrote {rep.n_aa} atoms to {a.out}", file=sys.stderr)
    if prot:
        print(f"  protein (heavy atoms, chains {', '.join(c for c, _ in rep.chains)}) -> {base}_protein.pdb", file=sys.stderr)
        if rest:
            print(f"  everything else -> {base}_nonprotein.gro", file=sys.stderr)
    if rep.pruned_waters:
        print(f"  removed {rep.pruned_waters} clashing waters", file=sys.stderr)
    for w in rep.warnings[:20]:
        print("WARNING:", w, file=sys.stderr)
    if len(rep.warnings) > 20:
        print(f"WARNING: ... and {len(rep.warnings) - 20} more", file=sys.stderr)
    for k, v in rep.skipped.items():
        print(f"WARNING: skipped {v} residue(s) {k} (no rule)", file=sys.stderr)
    print("\n[ molecules ] (order as in the output file)", file=sys.stderr)
    for name, n in rep.molecules:
        print(f"{name:<20s} {n:8d}", file=sys.stderr)
    return 0


def _cmd_make_map(a) -> int:
    s = read_structure(a.aa)
    res = s.residues
    if a.resnr is not None:
        res = [r for r in res if r.resnr == a.resnr]
    if len(res) != 1:
        # allow a multi-residue molecule: use all atoms
        print(f"Note: using all {sum(len(r.atoms) for r in res)} atoms of {len(res)} residues", file=sys.stderr)
    names = [at.name for r in res for at in r.atoms]
    xyz = np.array([at.xyz for r in res for at in r.atoms])
    if len(set(names)) != len(names):
        raise SystemExit("Atom names must be unique within the molecule")
    order, defs = read_bead_definitions(a.beads)
    resnames = a.name or [res[0].resname]
    t = make_map(names, xyz - xyz.mean(0), order, defs, resnames)
    t.write(a.out, comment=f"Generated by m3backmap {__version__} from {a.aa} and {a.beads}")
    print(f"Wrote {a.out}: {len(names)} atoms, {len(order)} beads, {len(t.bonds)} bonds", file=sys.stderr)
    return 0


def _cmd_merge(a) -> int:
    residues, box, n = [], None, 0
    for f in a.files:
        s = read_structure(f)
        residues += s.residues
        if np.any(s.box):
            box = s.box
    out = System("merged by m3backmap", residues, box if box is not None else np.zeros(3))
    write_structure(out, a.out)
    print(f"Wrote {out.n_atoms} atoms to {a.out}", file=sys.stderr)
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="m3backmap", description="Backmap Martini 3 CG structures to all-atom.")
    p.add_argument("--version", action="version", version=__version__)
    sub = p.add_subparsers(dest="cmd")

    b = sub.add_parser("backmap", help="backmap a CG structure", formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    b.add_argument("-c", "--cg", required=True, help="CG structure (.gro or .pdb)")
    b.add_argument("-o", "--out", default="aa.gro", help="output all-atom structure (.gro or .pdb)")
    b.add_argument("-m", "--maps", nargs="*", help="extra .map template files")
    b.add_argument("-d", "--mapdir", nargs="*", help="extra directories with .map files")
    b.add_argument("--itp", nargs="*", help="atomistic .itp files; residues are reordered to match their [ atoms ]")
    b.add_argument("--water", default="tip3p", choices=sorted(WATER_MODELS), help="water model geometry")
    b.add_argument("--water-resname", default="SOL")
    b.add_argument("--ions", default="charmm", choices=sorted(ION_NAMES), help="ion naming convention")
    b.add_argument("--ion-waters", type=int, default=0, help="waters added around each ion bead")
    b.add_argument("--prune-water", type=float, default=0.0,
                   help="remove waters with O closer than this (nm) to solute heavy atoms (0 = off)")
    b.add_argument("--no-relax", action="store_true", help="skip geometric relaxation")
    b.add_argument("--relax-iter", type=int, default=500)
    b.add_argument("--bb-break", type=float, default=0.6, help="BB-BB distance (nm) that starts a new chain")
    b.add_argument("--skip-unknown", action="store_true", help="drop residues without a rule instead of failing")
    b.add_argument("--keep-order", action="store_true",
                   help="keep the CG residue order instead of grouping molecules of the same type")
    b.add_argument("--seed", type=int, default=1)
    b.add_argument("-q", "--quiet", action="store_true")
    b.set_defaults(func=_cmd_backmap)

    m = sub.add_parser("make-map", help="create a .map template from an atomistic structure")
    m.add_argument("-f", "--aa", required=True, help="atomistic structure of ONE molecule (.pdb/.gro)")
    m.add_argument("-b", "--beads", required=True, help="bead definitions: '[ BEAD ]' followed by atom names")
    m.add_argument("-n", "--name", nargs="*", help="residue name(s) the template applies to")
    m.add_argument("-r", "--resnr", type=int, help="use only this residue number from the structure")
    m.add_argument("-o", "--out", required=True)
    m.set_defaults(func=_cmd_make_map)

    g = sub.add_parser("merge", help="concatenate structure files (box taken from the last one)")
    g.add_argument("-f", "--files", nargs="+", required=True)
    g.add_argument("-o", "--out", required=True)
    g.set_defaults(func=_cmd_merge)

    args = p.parse_args(argv)
    if not getattr(args, "cmd", None):
        p.print_help()
        return 1
    return args.func(args)
